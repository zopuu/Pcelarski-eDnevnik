using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using PcelarskiEDnevnik.Modules.Hives.Domain.HiveActions;

namespace PcelarskiEDnevnik.Modules.Hives.Infrastructure.Persistence.Configurations;

internal sealed class SuperManagementConfiguration
    : IEntityTypeConfiguration<SuperManagement> {
    public void Configure(
        EntityTypeBuilder<SuperManagement> builder) {
        builder.ToTable(
            "super_management",
            "hives",
            table => {
                table.Property(
                        x => x.Id)
                    .HasColumnName(
                        "action_id");
            });
    }
}
